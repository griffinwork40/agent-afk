/**
 * Durable pending-question store.
 *
 * History: introduced in #1416 as the foundational slice for crash-safe
 * elicitation recovery. Prior to this, pending human questions existed only
 * in process memory and were silently lost on restart.
 *
 * Contract:
 *   - Every question that reaches the elicitation router is written to SQLite
 *     (via the shared StateStore at kv.db) before the handler is called.
 *   - On resolution (answer, decline, cancel, skip, abort) the record is
 *     marked `resolved` and the `resolvedAt` timestamp is set. Records are
 *     NOT deleted so that post-mortem inspection is possible.
 *   - Questions are keyed by a caller-supplied `questionId` (typically the
 *     SDK's `elicitationId`, falling back to a UUID generated by the router).
 *   - The store is additive and dormant-safe: no existing router path changes
 *     user-visible behavior. Cross-restart reply routing is out of scope for
 *     this slice.
 *
 * Namespace: `"pending-questions"` in the shared kv.db.
 *
 * @module agent/elicitation/pending-question-store
 */

import { StateStore } from '../state/state-store.js';
import { getStateDatabasePath } from '../../paths.js';

export type PendingQuestionStatus = 'pending' | 'resolved';

export interface PendingQuestion {
  /** Stable identifier — SDK elicitationId or a generated UUID. */
  questionId: string;
  /** Session that generated the question. */
  sessionId: string | undefined;
  /**
   * Which AFK surface served the elicitation (e.g. `"repl"`, `"telegram"`,
   * `"daemon"`, `"unattended"`).
   */
  surface: string;
  /** The serialized elicitation prompt text. */
  prompt: string;
  /** ISO 8601 timestamp of when the question was recorded. */
  createdAt: string;
  status: PendingQuestionStatus;
  /** ISO 8601 timestamp of resolution; absent while status is `"pending"`. */
  resolvedAt?: string;
  /**
   * How the question was resolved: the elicitation action string, or
   * `"aborted"` when the turn's abort signal fired before the handler settled.
   */
  resolvedAction?: string;
}

const NAMESPACE = 'pending-questions';

/**
 * Maximum number of characters from the elicitation message stored as `prompt`.
 * Bounds inadvertent over-storage of large model-authored messages.
 */
const MAX_PROMPT_CHARS = 500;

// Invariant: _store is a process-global singleton shared across all concurrent
// surfaces in this process (REPL, Telegram, daemon). Consistent with the
// goal-store pattern — questions are cross-session state in kv.db.
let _store: StateStore | undefined;

function store(): StateStore {
  _store ??= new StateStore(getStateDatabasePath());
  return _store;
}

/**
 * Inject a custom StateStore for testing. Pass `undefined` to reset to the
 * default singleton so tests do not leak state between cases.
 */
export function _setStoreForTest(s: StateStore | undefined): void {
  _store = s;
}

/**
 * Truncate the prompt to the storage cap. Appends an ellipsis so readers
 * know the text was cut.
 */
function truncatePrompt(text: string): string {
  return text.length <= MAX_PROMPT_CHARS
    ? text
    : `${text.slice(0, MAX_PROMPT_CHARS)}\u2026`;
}

/**
 * Derive the StateStore key for a question. Keys must match `[A-Za-z0-9_.-]+`
 * and be at most 128 chars. The `qid-` prefix ensures the first character is
 * always a letter even when `questionId` starts with a digit.
 */
function toStoreKey(questionId: string): string {
  const sanitized = questionId
    .replace(/[^A-Za-z0-9_.-]/g, '-')
    .slice(0, 123);
  return `qid-${sanitized}`;
}

/**
 * Record a newly-arrived elicitation question in the durable store.
 *
 * Returns the stored `PendingQuestion`. If a record with this `questionId`
 * already exists (e.g. due to a retry in the same process), the existing
 * record is returned unchanged via `insertIfAbsent` semantics.
 *
 * @param questionId - Stable identifier for this question (SDK elicitationId
 *   or a generated UUID).
 * @param sessionId  - Session that generated the question (may be undefined
 *   when the router is called without a session context).
 * @param surface    - Which AFK surface is serving this elicitation.
 * @param prompt     - The human-readable elicitation message.
 */
export function recordQuestion(
  questionId: string,
  sessionId: string | undefined,
  surface: string,
  prompt: string,
): PendingQuestion {
  const key = toStoreKey(questionId);
  const existing = store().get(NAMESPACE, key);
  if (existing) return existing.value as PendingQuestion;

  const record: PendingQuestion = {
    questionId,
    sessionId,
    surface,
    prompt: truncatePrompt(prompt),
    createdAt: new Date().toISOString(),
    status: 'pending',
  };

  store().insertIfAbsent(NAMESPACE, key, record);
  // Re-read to get what was actually written (handles the race where two
  // callers insertIfAbsent simultaneously — one wins and one reads back the
  // winner's record).
  const after = store().get(NAMESPACE, key);
  return after ? (after.value as PendingQuestion) : record;
}

/**
 * Mark a previously-recorded question as resolved.
 *
 * Uses compare-and-swap so a concurrent resolver on a different surface does
 * not clobber a prior resolution. Returns `null` when the question is not
 * found or is already resolved (idempotent).
 *
 * @param questionId     - Same identifier passed to `recordQuestion`.
 * @param resolvedAction - How the question was resolved (elicitation action
 *   string or `"aborted"`).
 */
export function markResolved(
  questionId: string,
  resolvedAction: string,
): PendingQuestion | null {
  const key = toStoreKey(questionId);
  const row = store().get(NAMESPACE, key);
  if (!row) return null;

  const record = row.value as PendingQuestion;
  if (record.status === 'resolved') return record;

  const updated: PendingQuestion = {
    ...record,
    status: 'resolved',
    resolvedAt: new Date().toISOString(),
    resolvedAction,
  };

  const result = store().cas(NAMESPACE, key, row.version, updated);
  if (result.matched) return updated;

  // CAS missed — another resolver raced us. Re-read and return whatever won.
  const after = store().get(NAMESPACE, key);
  return after ? (after.value as PendingQuestion) : null;
}

/**
 * Retrieve a single pending-question record by its `questionId`. Returns
 * `null` when not found.
 */
export function getQuestion(questionId: string): PendingQuestion | null {
  const key = toStoreKey(questionId);
  const row = store().get(NAMESPACE, key);
  return row ? (row.value as PendingQuestion) : null;
}

/**
 * List questions in the store, newest first. Optionally filter by status.
 *
 * @param opts.status - When supplied, only questions with this status are
 *   returned.
 * @param opts.limit  - Maximum number of records to return (default 50).
 */
export function listQuestions(opts?: {
  status?: PendingQuestionStatus;
  limit?: number;
}): PendingQuestion[] {
  const limit = opts?.limit ?? 50;
  const rows = store().query(NAMESPACE, { limit });
  const questions = rows.map((r) => r.value as PendingQuestion);
  if (opts?.status !== undefined) {
    return questions.filter((q) => q.status === opts.status);
  }
  return questions;
}

/**
 * Close the underlying SQLite connection and reset the module singleton.
 * Required for test teardown on Windows where SQLite file handles prevent
 * directory deletion until the connection is explicitly closed.
 */
export function closeStore(): void {
  _store?.close();
  _store = undefined;
}
